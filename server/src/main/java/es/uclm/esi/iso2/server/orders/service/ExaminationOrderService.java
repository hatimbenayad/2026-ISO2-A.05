package es.uclm.esi.iso2.server.orders.service;

import es.uclm.esi.iso2.common.orders.contracts.IExaminationOrderService;
import es.uclm.esi.iso2.common.orders.domain.ExaminationOrder;
import es.uclm.esi.iso2.common.orders.domain.OrderStatus;
import es.uclm.esi.iso2.common.orders.domain.Priority;
import es.uclm.esi.iso2.common.orders.dto.ExaminationOrderDto;
import es.uclm.esi.iso2.common.orders.dto.ExaminationOrderRequest;
import es.uclm.esi.iso2.common.patients.domain.Patient;
import es.uclm.esi.iso2.server.orders.persistence.IOrderRepository;
import es.uclm.esi.iso2.server.patients.persistence.IPatientRepository;
import java.time.Clock;
import java.time.LocalDateTime;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.NoSuchElementException;
import java.util.Objects;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ConcurrentMap;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * Control_ManageOrders and Control_ProcedureExecution of the analysis: creates examination orders (CU10), registers
 * periodic follow-ups (CU11), lists and cancels orders (CU12) and records the execution of a scheduled examination
 * (CU16). Orders are never deleted, only cancelled (D-015).
 */
public class ExaminationOrderService implements IExaminationOrderService {
    /** Most urgent first; orders with the same priority keep the order of their ids. */
    private static final Comparator<ExaminationOrder> BY_PRIORITY_THEN_ID =
            Comparator.comparing(ExaminationOrder::getPriority).thenComparing(ExaminationOrder::getOrderId);

    private final IOrderRepository orderRepository;
    private final IPatientRepository patientRepository;
    private final Clock clock;
    private final AtomicInteger orderSequence = new AtomicInteger();
    private final AtomicInteger followUpSequence = new AtomicInteger();
    private final ConcurrentMap<String, PeriodicFollowUp> followUps = new ConcurrentHashMap<>();
    private final ConcurrentMap<String, ProcedureExecutionLog> executionLogs = new ConcurrentHashMap<>();

    public ExaminationOrderService(IOrderRepository orderRepository, IPatientRepository patientRepository) {
        this(orderRepository, patientRepository, Clock.systemDefaultZone());
    }

    /** The clock is a parameter so that the tests can fix the cancellation and execution dates. */
    public ExaminationOrderService(IOrderRepository orderRepository, IPatientRepository patientRepository,
            Clock clock) {
        this.orderRepository = Objects.requireNonNull(orderRepository, "orderRepository");
        this.patientRepository = Objects.requireNonNull(patientRepository, "patientRepository");
        this.clock = Objects.requireNonNull(clock, "clock");
    }

    // ---------------------------------------------------------------- CU10

    /**
     * CU10: creates an order in status ORDERED for an active patient.
     *
     * @throws IllegalArgumentException if a field is missing
     * @throws NoSuchElementException if the patient does not exist
     * @throws IllegalStateException if the patient is discharged
     */
    @Override
    public ExaminationOrderDto createOrder(ExaminationOrderRequest request) {
        if (request == null) {
            throw new IllegalArgumentException("Request cannot be null");
        }
        validateRequired(request.patientId(), "Patient ID");
        validateRequired(request.physicianId(), "Physician ID");
        validateRequired(request.modality(), "Modality");
        validateRequired(request.clinicalIndication(), "Clinical indication");
        if (request.priority() == null) {
            throw new IllegalArgumentException("Priority cannot be null");
        }
        String patientId = request.patientId().trim();
        requireActivePatient(patientId);

        ExaminationOrder order = new ExaminationOrder(nextOrderId(), patientId, request.physicianId().trim(),
                request.modality().trim(), request.clinicalIndication().trim(), request.priority());
        orderRepository.save(order);
        return ExaminationOrderDto.from(order);
    }

    // ---------------------------------------------------------------- CU11

    /**
     * CU11: registers a periodic follow-up with its recurrence interval. No order is created here: the future
     * orders are generated by the server Timer (SCU05).
     *
     * @throws IllegalArgumentException if a field is missing or the interval is not positive
     * @throws NoSuchElementException if the patient does not exist
     * @throws IllegalStateException if the patient is discharged
     */
    public PeriodicFollowUp registerFollowUp(ExaminationOrderRequest request, int intervalDays) {
        if (request == null) {
            throw new IllegalArgumentException("Request cannot be null");
        }
        if (intervalDays <= 0) {
            throw new IllegalArgumentException("The recurrence interval must be at least one day");
        }
        validateRequired(request.patientId(), "Patient ID");
        validateRequired(request.physicianId(), "Physician ID");
        validateRequired(request.modality(), "Modality");
        validateRequired(request.clinicalIndication(), "Clinical indication");
        String patientId = request.patientId().trim();
        requireActivePatient(patientId);

        Priority priority = request.priority() == null ? Priority.ROUTINE : request.priority();
        String followUpId = String.format("FUP-%04d", followUpSequence.incrementAndGet());
        PeriodicFollowUp followUp = new PeriodicFollowUp(followUpId, patientId, request.physicianId().trim(),
                request.modality().trim(), request.clinicalIndication().trim(), priority, intervalDays,
                LocalDateTime.now(clock));
        followUps.put(followUpId, followUp);
        return followUp;
    }

    /** The follow-ups of the patient, sorted by id. Empty when there are none. */
    public List<PeriodicFollowUp> getFollowUps(String patientId) {
        validateRequired(patientId, "Patient ID");
        String id = patientId.trim();
        return followUps.values().stream()
                .filter(followUp -> followUp.patientId().equals(id))
                .sorted(Comparator.comparing(PeriodicFollowUp::followUpId))
                .toList();
    }

    // ---------------------------------------------------------------- CU12

    /**
     * Lists orders, most urgent first. With a status only the orders in that status are returned; with
     * {@code null} every order is returned, cancelled ones included, so the physician sees each status (CU12).
     */
    @Override
    public List<ExaminationOrderDto> listOrders(OrderStatus status) {
        List<ExaminationOrder> orders = status == null ? findAllOrders() : orderRepository.findByStatus(status);
        return orders.stream().sorted(BY_PRIORITY_THEN_ID).map(ExaminationOrderDto::from).toList();
    }

    /** CU12 step 2: the orders prescribed by the physician, in every status, most urgent first. */
    public List<ExaminationOrderDto> findOrdersByPhysician(String physicianId) {
        validateRequired(physicianId, "Physician ID");
        String id = physicianId.trim();
        return findAllOrders().stream()
                .filter(order -> id.equals(order.getPhysicianId()))
                .sorted(BY_PRIORITY_THEN_ID)
                .map(ExaminationOrderDto::from)
                .toList();
    }

    /**
     * CU12: marks the order as CANCELLED with the current date; nothing is deleted (D-015). Its appointment is not
     * cancelled here, that is done by the administrative staff (CU22).
     *
     * @throws NoSuchElementException if the order does not exist
     * @throws IllegalStateException if the order is already cancelled
     */
    @Override
    public ExaminationOrderDto cancelOrder(String orderId) {
        validateRequired(orderId, "Order ID");
        ExaminationOrder order = requireOrder(orderId);
        order.cancel(LocalDateTime.now(clock));
        orderRepository.update(order);
        return ExaminationOrderDto.from(order);
    }

    // ---------------------------------------------------------------- CU16

    /**
     * CU16: records the execution parameters of a SCHEDULED order and moves it to PERFORMED.
     *
     * @param contrastVolumeMl {@code null} when no contrast medium was used
     * @throws IllegalArgumentException if the dose or the equipment are missing or invalid
     * @throws NoSuchElementException if the order does not exist
     * @throws IllegalStateException if the order is not SCHEDULED (cancelled, not yet scheduled or already
     *     performed)
     */
    public ExaminationOrderDto registerExecution(String orderId, Double effectiveDoseMsv, Double contrastVolumeMl,
            String equipmentId) {
        validateRequired(orderId, "Order ID");
        if (effectiveDoseMsv == null || effectiveDoseMsv < 0 || effectiveDoseMsv.isNaN()) {
            throw new IllegalArgumentException("Effective dose must be filled in and not negative");
        }
        validateRequired(equipmentId, "Equipment ID");
        if (contrastVolumeMl != null && (contrastVolumeMl <= 0 || contrastVolumeMl.isNaN())) {
            throw new IllegalArgumentException("Contrast volume must be positive when contrast is used");
        }

        ExaminationOrder order = requireOrder(orderId);
        if (order.getOrderStatus() != OrderStatus.SCHEDULED) {
            throw new IllegalStateException("Only scheduled orders can be performed; order " + order.getOrderId()
                    + " is " + order.getOrderStatus());
        }
        order.setOrderStatus(OrderStatus.PERFORMED);
        orderRepository.update(order);
        executionLogs.put(order.getOrderId(), new ProcedureExecutionLog(order.getOrderId(), effectiveDoseMsv,
                contrastVolumeMl, equipmentId.trim(), LocalDateTime.now(clock)));
        return ExaminationOrderDto.from(order);
    }

    /** The execution recorded for the order, or {@code null} when it has not been performed through CU16. */
    public ProcedureExecutionLog getExecutionLog(String orderId) {
        validateRequired(orderId, "Order ID");
        return executionLogs.get(orderId.trim());
    }

    // ---------------------------------------------------------------- helpers

    public ExaminationOrderDto getOrder(String orderId) {
        validateRequired(orderId, "Order ID");
        return ExaminationOrderDto.from(requireOrder(orderId));
    }

    private ExaminationOrder requireOrder(String orderId) {
        ExaminationOrder order = orderRepository.findById(orderId.trim());
        if (order == null) {
            throw new NoSuchElementException("Order not found: " + orderId);
        }
        return order;
    }

    private void requireActivePatient(String patientId) {
        Patient patient = patientRepository.findById(patientId);
        if (patient == null) {
            throw new NoSuchElementException("Patient not found: " + patientId);
        }
        if (!patient.isActive()) {
            throw new IllegalStateException("The patient " + patientId + " is discharged");
        }
    }

    /** The repository has no findAll, so all the statuses are read; cancelled orders are included (D-015). */
    private List<ExaminationOrder> findAllOrders() {
        return Arrays.stream(OrderStatus.values())
                .flatMap(status -> orderRepository.findByStatus(status).stream())
                .toList();
    }

    /** Skips ids that are already stored, for example orders saved directly in the repository. */
    private String nextOrderId() {
        String orderId;
        do {
            orderId = String.format("ORD-%04d", orderSequence.incrementAndGet());
        } while (orderRepository.existsById(orderId));
        return orderId;
    }

    private static void validateRequired(String value, String fieldName) {
        if (value == null || value.isBlank()) {
            throw new IllegalArgumentException(fieldName + " cannot be null or blank");
        }
    }
}
